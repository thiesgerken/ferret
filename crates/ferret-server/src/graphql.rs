fn parse_config(config: &str) -> FieldResult<serde_json::Value> {
    serde_json::from_str(config)
        .map_err(|error| invalid_input(format!("the config isn't JSON: {error}")))
}

fn parse_id(id: &ID) -> FieldResult<Uuid> {
    id.parse().map_err(|_| no_such_connection())
}

fn no_such_connection() -> FieldError {
    FieldError::new("no such connection", graphql_value!(null))
}

fn connection_error(error: ConnectionError) -> FieldError {
    match error {
        ConnectionError::Invalid(message) => invalid_input(message),
        ConnectionError::Database(error) => internal(error),
    }
}

fn require_admin(context: &Context) -> FieldResult<()> {
    if context.user.is_admin {
        Ok(())
    } else {
        Err(FieldError::new(
            "admins only",
            graphql_value!({ "code": "FORBIDDEN" }),
        ))
    }
}

fn parse_user_id(id: &ID) -> FieldResult<Uuid> {
    id.parse().map_err(|_| no_such_user())
}

fn no_such_user() -> FieldError {
    FieldError::new("no such user", graphql_value!(null))
}

fn user_error(error: UserError) -> FieldError {
    match error {
        UserError::Invalid(message) => invalid_input(message),
        UserError::Database(error) => internal(error),
    }
}

fn invalid_input(message: String) -> FieldError {
    FieldError::new(message, graphql_value!({ "code": "INVALID_INPUT" }))
}

/// Database failures are logged, the client only learns that something went wrong.
fn internal(error: sqlx::Error) -> FieldError {
    tracing::error!(%error, "database error");
    FieldError::new("internal error", graphql_value!(null))
}

