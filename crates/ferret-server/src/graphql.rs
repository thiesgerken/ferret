pub struct Query;

#[graphql_object(context = Context)]
impl Query {
    /// The signed-in user.
    fn me(context: &Context) -> &User {
        &context.user
    }

    /// The signed-in user's homepage totals, cached for 60 seconds.
    async fn index_summary(context: &Context) -> FieldResult<IndexSummary> {
        let totals = context
            .statistics
            .totals(&context.pool, context.user.id)
            .await
            .map_err(internal)?;
        Ok(IndexSummary {
            documents: count(totals.documents),
            chunks: count(totals.chunks),
            sources: count(totals.sources),
        })
    }

    /// Signed-in-user content by writer, cached for five seconds independently of ingest-feed filters.
    /// Storage is an attribution estimate in bytes, excluding the shared embedding cache.
    async fn writer_statistics(context: &Context) -> FieldResult<WriterStatistics> {
        let statistics = context
            .statistics
            .writers(&context.pool, context.user.id)
            .await
            .map_err(internal)?;
        Ok(WriterStatistics::from(statistics.as_ref()))
    }

    /// Every user. Admins only.
    async fn users(context: &Context) -> FieldResult<Vec<UserAccount>> {
        require_admin(context)?;
        let accounts = users::accounts(&context.pool).await.map_err(internal)?;
        Ok(accounts.into_iter().map(UserAccount::from).collect())
    }

    /// The plugin workers seen in the last day, the most recently seen first. Admins only.
    async fn workers(context: &Context) -> FieldResult<Vec<Worker>> {
        require_admin(context)?;
        let workers = runs::workers(&context.pool).await.map_err(internal)?;
        Ok(workers
            .into_iter()
            .map(|worker| Worker {
                id: ID::new(worker.id.to_string()),
                name: worker.name,
                plugins: worker.plugins,
                last_seen_at: worker.last_seen_at,
                online: worker.online,
            })
            .collect())
    }

    /// Plugin runs and bursts of API keys' writes, newest first: the signed-in user's, or every
    /// user's with `allUsers` (admins only, no when left out). `writer` filters by a connection's
    /// or key's id. For the next page, `before` takes the last ingest's `cursor`. `limit` is 1 to
    /// 200, 50 when left out.
    async fn activity(
        context: &Context,
        writer: Option<ID>,
        before: Option<String>,
        limit: Option<i32>,
        all_users: Option<bool>,
    ) -> FieldResult<Vec<Ingest>> {
        let limit = limit.unwrap_or(50);
        let all_users = all_users.unwrap_or(false);
        if all_users {
            require_admin(context)?;
        }
        if !(1..=200).contains(&limit) {
            return Err(invalid_input("limit must be between 1 and 200".to_owned()));
        }
        let filter = activity::FeedFilter {
            user_id: (!all_users).then_some(context.user.id),
            writer_id: writer.as_ref().map(parse_id).transpose()?,
            before: before
                .map(|cursor| {
                    activity::Cursor::decode(&cursor)
                        .ok_or_else(|| invalid_input("not a cursor of this feed".to_owned()))
                })
                .transpose()?,
            limit: i64::from(limit),
        };
        let ingests = activity::feed(&context.pool, &filter)
            .await
            .map_err(internal)?;
        Ok(ingests
            .into_iter()
            .map(|ingest| Ingest {
                owner: all_users.then(|| ingest.owner.clone()),
                ingest,
            })
            .collect())
    }

    /// Each embedding model's backlog, the default first. Admins only.
    async fn embedding_status(context: &Context) -> FieldResult<Vec<ModelStatus>> {
        require_admin(context)?;
        let statuses = context
            .embedding
            .status(&context.pool, &context.statistics)
            .await
            .map_err(internal)?;
        Ok(statuses.into_iter().map(ModelStatus::from).collect())
    }

    /// Every embedding model that has embedded, configured or not, the configured ones first.
    /// Cached for five seconds. Admins only.
    async fn stored_embedding_models(context: &Context) -> FieldResult<Vec<StoredEmbeddingModel>> {
        require_admin(context)?;
        let models = context
            .statistics
            .global(&context.pool, &context.embedding)
            .await
            .map_err(internal)?;
        Ok(models
            .stored
            .iter()
            .map(StoredEmbeddingModel::from)
            .collect())
    }

    /// The signed-in user's API keys, newest first.
    async fn api_keys(context: &Context) -> FieldResult<Vec<ApiKey>> {
        api_keys::list(&context.pool, context.user.id)
            .await
            .map_err(internal)
    }

    /// Searches the signed-in user's documents, one hit per document. The same search as
    /// `GET /api/search`.
    async fn search(context: &Context, input: SearchInput) -> FieldResult<SearchResult> {
        let (request, range) = input.resolve(Utc::now())?;
        let response = search::find(
            &context.pool,
            &context.embedding,
            &context.statistics,
            context.user.id,
            None,
            &request,
        )
        .await
        .map_err(search_error)?;
        let judged = judgments::judged_documents(&context.pool, context.user.id, &request, range)
            .await
            .map_err(internal)?;
        Ok(SearchResult {
            hits: response
                .hits
                .into_iter()
                .map(|hit| Hit {
                    judged: judged.contains(&hit.document_id),
                    ..Hit::from(hit)
                })
                .collect(),
            total: graphql_int(response.total),
            total_is_lower_bound: response.total_is_lower_bound,
            documents_in_scope: graphql_int(response.documents_in_scope),
            has_more: response.has_more,
            facets: SearchFacets {
                sources: source_counts(response.facets.sources),
                authors: search_facet_counts(response.facets.authors),
                are_lower_bounds: response.facets.are_lower_bounds,
            },
            took_ms: graphql_int(response.took_ms),
            semantic_unavailable: response.semantic_unavailable,
            model: response.model,
        })
    }

    /// The signed-in user's documents without a query: a page of them, how many there are, and
    /// facet counts. The filters mean what search's mean.
    async fn explore(context: &Context, input: ExploreInput) -> FieldResult<Exploration> {
        let filter = ExploreFilter {
            sources: input.sources.unwrap_or_default(),
            content_types: input
                .content_types
                .unwrap_or_default()
                .into_iter()
                .map(ferret_api::ContentType::from)
                .collect(),
            authors: input.authors.unwrap_or_default(),
            from: input.from,
            to: input.to,
        };
        let page = Page {
            order: match input.order_by.unwrap_or(DocumentOrder::CreatedAt) {
                DocumentOrder::CreatedAt => Order::CreatedAt,
                DocumentOrder::ModifiedAt => Order::ModifiedAt,
                DocumentOrder::Title => Order::Title,
                DocumentOrder::Source => Order::Source,
            },
            descending: input.descending.unwrap_or(true),
            offset: input.offset.unwrap_or(0).into(),
            limit: input.limit.unwrap_or(DEFAULT_EXPLORE_LIMIT).into(),
        };
        match explore::explore(&context.pool, context.user.id, &filter, &page).await {
            Ok(exploration) => Ok(Exploration::from(exploration)),
            Err(ExploreError::Invalid(message)) => Err(invalid_input(message)),
            Err(ExploreError::Database(error)) => Err(internal(error)),
        }
    }

    /// The configured embedding models, the configured default first, with how much of the
    /// signed-in user's data each covers.
    fn embedding_models(context: &Context) -> Vec<EmbeddingModel> {
        let default = context.embedding.default_model().id();
        context
            .embedding
            .models()
            .iter()
            .map(|model| EmbeddingModel {
                id: model.id().to_owned(),
                configured_default: model.id() == default,
                min_similarity: model.config.min_similarity,
                progress: OnceCell::new(),
            })
            .collect()
    }

    /// One of the signed-in user's documents, null when there is none with this id.
    async fn document(context: &Context, id: ID) -> FieldResult<Option<Document>> {
        let Ok(id) = id.parse::<Uuid>() else {
            return Ok(None);
        };
        let Some(document) = documents::find(&context.pool, context.user.id, None, id)
            .await
            .map_err(internal)?
        else {
            return Ok(None);
        };
        let neighbors = documents::thread_neighbors(&context.pool, context.user.id, &document)
            .await
            .map_err(internal)?;
        Ok(Some(Document::new(document, neighbors)))
    }

    /// The plugins that registered workers offer, with their config schemas.
    async fn plugin_types(context: &Context) -> FieldResult<Vec<PluginType>> {
        connections::plugin_types(&context.pool)
            .await
            .map_err(internal)
    }

    /// The signed-in user's connections, by source.
    async fn connections(context: &Context) -> FieldResult<Vec<Connection>> {
        connections::list(&context.pool, context.user.id)
            .await
            .map_err(internal)
    }

    async fn connection(context: &Context, id: ID) -> FieldResult<Option<Connection>> {
        let Ok(id) = id.parse::<Uuid>() else {
            return Ok(None);
        };
        connections::find(&context.pool, context.user.id, id)
            .await
            .map_err(internal)
    }
}

