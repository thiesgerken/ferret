/// GraphQL's `Int` is 32 bits. Chunk offsets beyond that would need a 2 GB document.
fn graphql_int(offset: u32) -> i32 {
    i32::try_from(offset).expect("chunk offsets fit into 32 bits")
}

pub struct Mutation;

#[derive(GraphQLInputObject)]
struct NewApiKey {
    name: String,
    scopes: Vec<Scope>,
    /// Restricts every scope to these source paths and below. Leave out for all sources.
    sources: Option<Vec<String>>,
    expires_at: Option<DateTime<Utc>>,
}

/// A new key, with the full key string. The only time it is shown.
struct CreatedApiKey {
    api_key: ApiKey,
    key: String,
}

#[graphql_object(context = Context)]
impl Mutation {
    /// Creates a connection, which runs right away and then on its schedule.
    async fn create_connection(context: &Context, input: NewConnection) -> FieldResult<Connection> {
        let new = connections::NewConnection {
            plugin: input.plugin,
            source: input.source,
            config: parse_config(&input.config)?,
            schedule: input.schedule,
        };
        connections::create(&context.pool, context.user.id, new)
            .await
            .map_err(connection_error)
    }

    async fn update_connection(
        context: &Context,
        id: ID,
        input: ConnectionUpdate,
    ) -> FieldResult<Connection> {
        let update = connections::ConnectionUpdate {
            config: parse_config(&input.config)?,
            schedule: input.schedule,
            enabled: input.enabled,
        };
        connections::update(&context.pool, context.user.id, parse_id(&id)?, update)
            .await
            .map_err(connection_error)?
            .ok_or_else(no_such_connection)
    }

    /// Starts a run without waiting for the schedule. Fails for a disabled connection.
    async fn run_connection_now(context: &Context, id: ID) -> FieldResult<ID> {
        if connections::run_now(&context.pool, context.user.id, parse_id(&id)?)
            .await
            .map_err(internal)?
        {
            Ok(id)
        } else {
            Err(FieldError::new(
                "no such enabled connection",
                graphql_value!(null),
            ))
        }
    }

    /// Deletes the connection and every document below its source root, once `confirmSource`
    /// repeats the root. Returns how many documents were deleted.
    async fn delete_connection(
        context: &Context,
        id: ID,
        confirm_source: String,
    ) -> FieldResult<i32> {
        let deleted = connections::delete(
            &context.pool,
            context.user.id,
            parse_id(&id)?,
            &confirm_source,
        )
        .await
        .map_err(connection_error)?
        .ok_or_else(no_such_connection)?;
        Ok(i32::try_from(deleted).unwrap_or(i32::MAX))
    }

    /// Admins only.
    async fn create_user(context: &Context, input: NewUser) -> FieldResult<UserAccount> {
        require_admin(context)?;
        let new = users::NewUser {
            username: input.username,
            display_name: input.display_name,
            password: input.password,
            is_admin: input.is_admin,
        };
        users::create(&context.pool, new)
            .await
            .map(UserAccount::from)
            .map_err(user_error)
    }

    /// Sets a user's password and signs them out everywhere. Admins only.
    async fn set_user_password(context: &Context, id: ID, password: String) -> FieldResult<ID> {
        require_admin(context)?;
        let user_id = parse_user_id(&id)?;
        if users::set_password(&context.pool, user_id, password)
            .await
            .map_err(user_error)?
        {
            Ok(id)
        } else {
            Err(no_such_user())
        }
    }

    /// Changes a user's display name, admin role and whether they can sign in. The last enabled
    /// admin can't be demoted or disabled. Admins only.
    async fn update_user(context: &Context, id: ID, input: UserUpdate) -> FieldResult<UserAccount> {
        require_admin(context)?;
        let update = users::UserUpdate {
            display_name: input.display_name,
            is_admin: input.is_admin,
            enabled: input.enabled,
        };
        users::update(&context.pool, parse_user_id(&id)?, update)
            .await
            .map_err(user_error)?
            .map(UserAccount::from)
            .ok_or_else(no_such_user)
    }

    async fn create_api_key(context: &Context, input: NewApiKey) -> FieldResult<CreatedApiKey> {
        let new = api_keys::NewApiKey {
            name: input.name,
            scopes: input.scopes,
            sources: input.sources,
            expires_at: input.expires_at,
        };
        match api_keys::create(&context.pool, &context.user, new).await {
            Ok((api_key, key)) => Ok(CreatedApiKey { api_key, key }),
            Err(api_keys::CreateError::Invalid(message)) => Err(invalid_input(message)),
            Err(api_keys::CreateError::Database(error)) => Err(internal(error)),
        }
    }

    /// Revokes one of the signed-in user's keys and returns its id.
    async fn revoke_api_key(context: &Context, id: ID) -> FieldResult<ID> {
        let not_found = || FieldError::new("no such API key", graphql_value!(null));
        let key_id = id.parse::<Uuid>().map_err(|_| not_found())?;
        if api_keys::revoke(&context.pool, context.user.id, key_id)
            .await
            .map_err(internal)?
        {
            Ok(id)
        } else {
            Err(not_found())
        }
    }
}

