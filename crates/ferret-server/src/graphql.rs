/// POST with a JSON body only: no GET, no `application/graphql`, no forms. Together with the
/// `SameSite=Lax` cookie that keeps cross-site requests from riding on a session.
pub async fn handle(
    State(state): State<AppState>,
    headers: HeaderMap,
    request: Result<Json<http::GraphQLRequest>, JsonRejection>,
) -> Result<(StatusCode, Json<http::GraphQLResponse>), ApiError> {
    let user = auth::signed_in_user(&state, &headers)
        .await?
        .ok_or_else(|| ApiError::unauthorized("not signed in"))?;
    let Json(request) = request?;
    let context = Context {
        user,
        pool: state.pool.clone(),
        embedding: state.embedding.clone(),
    };
    let response = request.execute(&state.schema, &context).await;
    let status = if response.is_ok() {
        StatusCode::OK
    } else {
        StatusCode::BAD_REQUEST
    };
    Ok((status, Json(response)))
}

