pub type Schema = RootNode<Query, Mutation, EmptySubscription<Context>>;

pub fn schema() -> Schema {
    Schema::new(Query, Mutation, EmptySubscription::new())
}

/// The SDL that `ferret schema` prints into `frontend/schema.graphql` for the frontend's codegen.
pub fn sdl() -> String {
    format!(
        "# Generated by `ferret schema`, don't edit. CI fails when it's out of date.\n\n{}",
        schema().as_sdl()
    )
}

pub struct Context {
    user: User,
    pool: PgPool,
    embedding: Arc<Embedding>,
}

impl juniper::Context for Context {}

pub struct Query;

#[graphql_object(context = Context)]
impl Query {
    /// The signed-in user.
    fn me(context: &Context) -> &User {
        &context.user
    }

    /// The signed-in user's API keys, newest first.
    async fn api_keys(context: &Context) -> FieldResult<Vec<ApiKey>> {
        api_keys::list(&context.pool, context.user.id)
            .await
            .map_err(internal)
    }

    /// Searches the signed-in user's documents, one hit per document. The same search as
    /// `GET /api/search`.
    async fn search(context: &Context, input: SearchInput) -> FieldResult<SearchResult> {
        let request = ferret_api::SearchQuery::from(input);
        let response = match search::find(
            &context.pool,
            &context.embedding,
            context.user.id,
            None,
            &request,
        )
        .await
        {
            Ok(response) => response,
            Err(SearchError::Invalid(message)) => return Err(invalid_input(message)),
            Err(SearchError::Database(error)) => return Err(internal(error)),
        };
        let judged = judgments::judged_documents(&context.pool, context.user.id, &request)
            .await
            .map_err(internal)?;
        Ok(SearchResult {
            hits: response
                .hits
                .into_iter()
                .map(|hit| Hit {
                    judged: judged.contains(&hit.document_id),
                    ..Hit::from(hit)
                })
                .collect(),
            semantic_unavailable: response.semantic_unavailable,
        })
    }

    /// One of the signed-in user's documents, null when there is none with this id.
    async fn document(context: &Context, id: ID) -> FieldResult<Option<Document>> {
        let Ok(id) = id.parse::<Uuid>() else {
            return Ok(None);
        };
        let document = documents::find(&context.pool, context.user.id, None, id)
            .await
            .map_err(internal)?;
        Ok(document.map(Document::from))
    }
}

#[derive(GraphQLInputObject)]
struct SearchInput {
    /// Words, `"exact phrases"` and `-excluded` words.
    q: String,
    /// Only documents in these sources or below them. Leave out for all sources.
    sources: Option<Vec<String>>,
    /// Only documents with at least one of these authors. Leave out for any author.
    authors: Option<Vec<String>>,
    /// Only documents of these content types. Leave out for all.
    content_types: Option<Vec<ContentType>>,
    /// Only documents created at or after this time.
    from: Option<DateTime<Utc>>,
    /// Only documents created before this time.
    to: Option<DateTime<Utc>>,
    /// How many hits at most, 1 to 100. The server's default applies when left out.
    k: Option<i32>,
}

impl From<SearchInput> for ferret_api::SearchQuery {
    fn from(input: SearchInput) -> Self {
        Self {
            q: input.q,
            sources: input.sources.unwrap_or_default(),
            authors: input.authors.unwrap_or_default(),
            content_types: input
                .content_types
                .unwrap_or_default()
                .into_iter()
                .map(ferret_api::ContentType::from)
                .collect(),
            from: input.from,
            to: input.to,
            // A negative k becomes 0, which the search rejects like any k out of range.
            k: input.k.map(|k| u32::try_from(k).unwrap_or(0)),
        }
    }
}

/// How the viewer renders a document.
#[derive(GraphQLEnum)]
enum ContentType {
    Markdown,
    Plain,
    Email,
}

impl From<ContentType> for ferret_api::ContentType {
    fn from(content_type: ContentType) -> Self {
        match content_type {
            ContentType::Markdown => Self::Markdown,
            ContentType::Plain => Self::Plain,
            ContentType::Email => Self::Email,
        }
    }
}

impl From<ferret_api::ContentType> for ContentType {
    fn from(content_type: ferret_api::ContentType) -> Self {
        match content_type {
            ferret_api::ContentType::Markdown => Self::Markdown,
            ferret_api::ContentType::Plain => Self::Plain,
            ferret_api::ContentType::Email => Self::Email,
        }
    }
}

/// The hits of a search, and whether its semantic half ran.
#[derive(GraphQLObject)]
struct SearchResult {
    hits: Vec<Hit>,
    /// Why the semantic half didn't run (e.g. the embedding model is down), so the hits are
    /// keyword matches only. Null when it ran.
    semantic_unavailable: Option<String>,
}

/// A document returned by a search, with its best-matching chunk.
#[derive(GraphQLObject)]
struct Hit {
    document_id: ID,
    source: String,
    external_id: String,
    content_type: ContentType,
    title: Option<String>,
    /// Deep link to the origin, null when ferret's viewer is the origin.
    url: Option<String>,
    thread: Option<String>,
    authors: Vec<String>,
    created_at: DateTime<Utc>,
    modified_at: DateTime<Utc>,
    score: f64,
    chunk: HitChunk,
    /// Whether the signed-in user marked this document as the right hit for this very search.
    judged: bool,
}

/// The best-matching chunk of a hit. Offsets count characters (Unicode code points) into the
/// document's text.
#[derive(GraphQLObject)]
struct HitChunk {
    start_offset: i32,
    end_offset: i32,
    /// The chunk's text, cut into parts that match the query and parts that don't.
    parts: Vec<TextPart>,
}

#[derive(GraphQLObject)]
struct TextPart {
    text: String,
    highlight: bool,
}

impl From<ferret_api::Hit> for Hit {
    fn from(hit: ferret_api::Hit) -> Self {
        Self {
            document_id: ID::new(hit.document_id.to_string()),
            source: hit.source,
            external_id: hit.external_id,
            content_type: hit.content_type.into(),
            title: hit.title,
            url: hit.url,
            thread: hit.thread,
            authors: hit.authors,
            created_at: hit.created_at,
            modified_at: hit.modified_at,
            score: hit.score.into(),
            judged: false,
            chunk: HitChunk {
                start_offset: graphql_int(hit.chunk.start_offset),
                end_offset: graphql_int(hit.chunk.end_offset),
                parts: hit
                    .chunk
                    .parts
                    .into_iter()
                    .map(|part| TextPart {
                        text: part.text,
                        highlight: part.highlight,
                    })
                    .collect(),
            },
        }
    }
}

#[derive(GraphQLObject)]
struct Document {
    id: ID,
    source: String,
    external_id: String,
    content_type: ContentType,
    title: Option<String>,
    text: String,
    /// Deep link to the origin, null when ferret's viewer is the origin.
    url: Option<String>,
    thread: Option<String>,
    authors: Vec<String>,
    created_at: DateTime<Utc>,
    modified_at: DateTime<Utc>,
}

impl From<ferret_api::Document> for Document {
    fn from(document: ferret_api::Document) -> Self {
        Self {
            id: ID::new(document.id.to_string()),
            source: document.source,
            external_id: document.external_id,
            content_type: document.content_type.into(),
            title: document.title,
            text: document.text,
            url: document.url,
            thread: document.thread,
            authors: document.authors,
            created_at: document.created_at,
            modified_at: document.modified_at,
        }
    }
}

/// GraphQL's `Int` is 32 bits. Chunk offsets beyond that would need a 2 GB document.
fn graphql_int(offset: u32) -> i32 {
    i32::try_from(offset).expect("chunk offsets fit into 32 bits")
}

pub struct Mutation;

/// A ✓ on a hit, or taking it back.
#[derive(GraphQLInputObject)]
struct JudgmentInput {
    /// The search the hit answered, as it was passed to `search`.
    search: SearchInput,
    document_id: ID,
    /// Whether the document is the right hit for the search.
    judged: bool,
}

#[derive(GraphQLInputObject)]
struct NewApiKey {
    name: String,
    scopes: Vec<Scope>,
    /// Restricts every scope to these source paths and below. Leave out for all sources.
    sources: Option<Vec<String>>,
    expires_at: Option<DateTime<Utc>>,
}

/// A new key, with the full key string. The only time it is shown.
struct CreatedApiKey {
    api_key: ApiKey,
    key: String,
}

#[graphql_object(context = Context)]
impl Mutation {
    /// Marks a document as the right hit for a search, or takes that back. Returns `judged`.
    /// Model evaluation replays the judged searches.
    async fn set_judgment(context: &Context, input: JudgmentInput) -> FieldResult<bool> {
        let document_id = input
            .document_id
            .parse::<Uuid>()
            .map_err(|_| invalid_input("no such document".to_owned()))?;
        let search = ferret_api::SearchQuery::from(input.search);
        let owned = judgments::set(
            &context.pool,
            context.user.id,
            &search,
            document_id,
            input.judged,
        )
        .await
        .map_err(internal)?;
        if !owned {
            return Err(invalid_input("no such document".to_owned()));
        }
        Ok(input.judged)
    }

    async fn create_api_key(context: &Context, input: NewApiKey) -> FieldResult<CreatedApiKey> {
        let new = api_keys::NewApiKey {
            name: input.name,
            scopes: input.scopes,
            sources: input.sources,
            expires_at: input.expires_at,
        };
        match api_keys::create(&context.pool, &context.user, new).await {
            Ok((api_key, key)) => Ok(CreatedApiKey { api_key, key }),
            Err(api_keys::CreateError::Invalid(message)) => Err(invalid_input(message)),
            Err(api_keys::CreateError::Database(error)) => Err(internal(error)),
        }
    }

    /// Revokes one of the signed-in user's keys and returns its id.
    async fn revoke_api_key(context: &Context, id: ID) -> FieldResult<ID> {
        let not_found = || FieldError::new("no such API key", graphql_value!(null));
        let key_id = id.parse::<Uuid>().map_err(|_| not_found())?;
        if api_keys::revoke(&context.pool, context.user.id, key_id)
            .await
            .map_err(internal)?
        {
            Ok(id)
        } else {
            Err(not_found())
        }
    }
}

#[graphql_object(context = Context)]
impl CreatedApiKey {
    fn api_key(&self) -> &ApiKey {
        &self.api_key
    }

    /// `fk_<prefix>.<secret>`, for `Authorization: Bearer`.
    fn key(&self) -> &str {
        &self.key
    }
}

#[graphql_object(context = Context)]
impl ApiKey {
    fn id(&self) -> ID {
        ID::new(self.id.to_string())
    }

    fn name(&self) -> &str {
        &self.name
    }

    /// The non-secret part after `fk_`, to tell keys apart.
    fn prefix(&self) -> &str {
        &self.prefix
    }

    fn scopes(&self) -> &[Scope] {
        &self.scopes
    }

    /// Source paths every scope is restricted to, null for all sources.
    fn sources(&self) -> Option<&[String]> {
        self.sources.as_deref()
    }

    fn created_at(&self) -> DateTime<Utc> {
        self.created_at
    }

    /// Updated at most once a minute.
    fn last_used_at(&self) -> Option<DateTime<Utc>> {
        self.last_used_at
    }

    fn expires_at(&self) -> Option<DateTime<Utc>> {
        self.expires_at
    }
}

fn invalid_input(message: String) -> FieldError {
    FieldError::new(message, graphql_value!({ "code": "INVALID_INPUT" }))
}

/// Database failures are logged, the client only learns that something went wrong.
fn internal(error: sqlx::Error) -> FieldError {
    tracing::error!(%error, "database error");
    FieldError::new("internal error", graphql_value!(null))
}

#[graphql_object(context = Context)]
impl User {
    fn id(&self) -> ID {
        ID::new(self.id.to_string())
    }

    fn username(&self) -> &str {
        &self.username
    }

    fn display_name(&self) -> Option<&str> {
        self.display_name.as_deref()
    }

    fn is_admin(&self) -> bool {
        self.is_admin
    }
}

/// POST with a JSON body only: no GET, no `application/graphql`, no forms. Together with the
/// `SameSite=Lax` cookie that keeps cross-site requests from riding on a session.
pub async fn handle(
    State(state): State<AppState>,
    headers: HeaderMap,
    request: Result<Json<http::GraphQLRequest>, JsonRejection>,
) -> Result<(StatusCode, Json<http::GraphQLResponse>), ApiError> {
    let user = auth::signed_in_user(&state, &headers)
        .await?
        .ok_or_else(|| ApiError::unauthorized("not signed in"))?;
    let Json(request) = request?;
    let context = Context {
        user,
        pool: state.pool.clone(),
        embedding: state.embedding.clone(),
    };
    let response = request.execute(&state.schema, &context).await;
    let status = if response.is_ok() {
        StatusCode::OK
    } else {
        StatusCode::BAD_REQUEST
    };
    Ok((status, Json(response)))
}
