pub type Schema = RootNode<Query, Mutation, EmptySubscription<Context>>;

pub fn schema() -> Schema {
    Schema::new(Query, Mutation, EmptySubscription::new())
}

/// The SDL that `ferret schema` prints into `frontend/schema.graphql` for the frontend's codegen.
pub fn sdl() -> String {
    format!(
        "# Generated by `ferret schema`, don't edit. CI fails when it's out of date.\n\n{}",
        schema().as_sdl()
    )
}

pub struct Context {
    user: User,
    pool: PgPool,
    embedding: Arc<Embedding>,
}

impl juniper::Context for Context {}

pub struct Query;

#[graphql_object(context = Context)]
impl Query {
    /// The signed-in user.
    fn me(context: &Context) -> &User {
        &context.user
    }

    /// Every user. Admins only.
    async fn users(context: &Context) -> FieldResult<Vec<UserAccount>> {
        require_admin(context)?;
        let accounts = users::accounts(&context.pool).await.map_err(internal)?;
        Ok(accounts.into_iter().map(UserAccount::from).collect())
    }

    /// The plugin workers seen in the last day, the most recently seen first. Admins only.
    async fn workers(context: &Context) -> FieldResult<Vec<Worker>> {
        require_admin(context)?;
        let workers = runs::workers(&context.pool).await.map_err(internal)?;
        Ok(workers
            .into_iter()
            .map(|worker| Worker {
                id: ID::new(worker.id.to_string()),
                name: worker.name,
                plugins: worker.plugins,
                last_seen_at: worker.last_seen_at,
            })
            .collect())
    }

    /// Each embedding model's TEI health and backlog, the default first. Admins only.
    async fn embedding_status(context: &Context) -> FieldResult<Vec<ModelStatus>> {
        require_admin(context)?;
        let statuses = context
            .embedding
            .status(&context.pool)
            .await
            .map_err(internal)?;
        Ok(statuses.into_iter().map(ModelStatus::from).collect())
    }

    /// The signed-in user's API keys, newest first.
    async fn api_keys(context: &Context) -> FieldResult<Vec<ApiKey>> {
        api_keys::list(&context.pool, context.user.id)
            .await
            .map_err(internal)
    }

    /// Searches the signed-in user's documents, one hit per document. The same search as
    /// `GET /api/search`.
    async fn search(context: &Context, input: SearchInput) -> FieldResult<SearchResult> {
        let request = ferret_api::SearchQuery {
            q: input.q,
            sources: input.sources.unwrap_or_default(),
            authors: input.authors.unwrap_or_default(),
            content_types: input
                .content_types
                .unwrap_or_default()
                .into_iter()
                .map(ferret_api::ContentType::from)
                .collect(),
            from: input.from,
            to: input.to,
            // A negative k becomes 0, which the search rejects like any k out of range.
            k: input.k.map(|k| u32::try_from(k).unwrap_or(0)),
        };
        match search::find(
            &context.pool,
            &context.embedding,
            context.user.id,
            None,
            &request,
        )
        .await
        {
            Ok(response) => Ok(SearchResult {
                hits: response.hits.into_iter().map(Hit::from).collect(),
                semantic_unavailable: response.semantic_unavailable,
            }),
            Err(SearchError::Invalid(message)) => Err(invalid_input(message)),
            Err(SearchError::Database(error)) => Err(internal(error)),
        }
    }

    /// One of the signed-in user's documents, null when there is none with this id.
    async fn document(context: &Context, id: ID) -> FieldResult<Option<Document>> {
        let Ok(id) = id.parse::<Uuid>() else {
            return Ok(None);
        };
        let document = documents::find(&context.pool, context.user.id, None, id)
            .await
            .map_err(internal)?;
        Ok(document.map(Document::from))
    }

    /// The plugins that registered workers offer, with their config schemas.
    async fn plugin_types(context: &Context) -> FieldResult<Vec<PluginType>> {
        connections::plugin_types(&context.pool)
            .await
            .map_err(internal)
    }

    /// The signed-in user's connections, by source.
    async fn connections(context: &Context) -> FieldResult<Vec<Connection>> {
        connections::list(&context.pool, context.user.id)
            .await
            .map_err(internal)
    }

    async fn connection(context: &Context, id: ID) -> FieldResult<Option<Connection>> {
        let Ok(id) = id.parse::<Uuid>() else {
            return Ok(None);
        };
        connections::find(&context.pool, context.user.id, id)
            .await
            .map_err(internal)
    }
}

