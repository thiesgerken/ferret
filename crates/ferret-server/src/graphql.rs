pub type Schema = RootNode<Query, Mutation, EmptySubscription<Context>>;

pub fn schema() -> Schema {
    Schema::new(Query, Mutation, EmptySubscription::new())
}

/// The SDL that `ferret schema` prints into `frontend/schema.graphql` for the frontend's codegen.
pub fn sdl() -> String {
    format!(
        "# Generated by `ferret schema`, don't edit. CI fails when it's out of date.\n\n{}",
        schema().as_sdl()
    )
}

pub struct Context {
    user: User,
    pool: PgPool,
}

impl juniper::Context for Context {}

pub struct Query;

#[graphql_object(context = Context)]
impl Query {
    /// The signed-in user.
    fn me(context: &Context) -> &User {
        &context.user
    }

    /// The signed-in user's API keys, newest first.
    async fn api_keys(context: &Context) -> FieldResult<Vec<ApiKey>> {
        api_keys::list(&context.pool, context.user.id)
            .await
            .map_err(internal)
    }

    /// The plugins that registered workers offer, with their config schemas.
    async fn plugin_types(context: &Context) -> FieldResult<Vec<PluginType>> {
        connections::plugin_types(&context.pool)
            .await
            .map_err(internal)
    }

    /// The signed-in user's connections, by source.
    async fn connections(context: &Context) -> FieldResult<Vec<Connection>> {
        connections::list(&context.pool, context.user.id)
            .await
            .map_err(internal)
    }

    async fn connection(context: &Context, id: ID) -> FieldResult<Option<Connection>> {
        let Ok(id) = id.parse::<Uuid>() else {
            return Ok(None);
        };
        connections::find(&context.pool, context.user.id, id)
            .await
            .map_err(internal)
    }
}

#[graphql_object(context = Context)]
impl PluginType {
    fn name(&self) -> &str {
        &self.name
    }

    /// JSON Schema of the config, as JSON text. Secret fields are `writeOnly`.
    fn config_schema(&self) -> String {
        self.config_schema.to_string()
    }
}

#[graphql_object(context = Context)]
impl Connection {
    fn id(&self) -> ID {
        ID::new(self.id.to_string())
    }

    fn plugin(&self) -> &str {
        &self.plugin
    }

    /// The source root the connection owns: it writes to it and below it.
    fn source(&self) -> &str {
        &self.source
    }

    /// The plugin config, as JSON text.
    fn config(&self) -> String {
        self.config.to_string()
    }

    /// Cron expression.
    fn schedule(&self) -> &str {
        &self.schedule
    }

    fn enabled(&self) -> bool {
        self.enabled
    }

    fn next_run_at(&self) -> DateTime<Utc> {
        self.next_run_at
    }

    fn created_at(&self) -> DateTime<Utc> {
        self.created_at
    }

    /// The latest runs, newest first.
    async fn runs(
        &self,
        context: &Context,
        #[graphql(default = 20)] limit: i32,
    ) -> FieldResult<Vec<PluginRun>> {
        connections::runs(&context.pool, self.id, i64::from(limit.clamp(1, 100)))
            .await
            .map_err(internal)
    }
}

#[derive(GraphQLEnum)]
enum RunStatus {
    Running,
    Succeeded,
    Failed,
    /// The worker stopped sending heartbeats.
    Lost,
}

/// What a run did to the index.
#[derive(GraphQLObject)]
struct RunStats {
    put: i32,
    unchanged: i32,
    deleted: i32,
}

#[graphql_object(context = Context)]
impl PluginRun {
    fn id(&self) -> ID {
        ID::new(self.id.to_string())
    }

    fn status(&self) -> RunStatus {
        match self.status.as_str() {
            "running" => RunStatus::Running,
            "succeeded" => RunStatus::Succeeded,
            "failed" => RunStatus::Failed,
            "lost" => RunStatus::Lost,
            // The table's check constraint admits no other value.
            status => panic!("unknown run status {status:?} in the database"),
        }
    }

    fn started_at(&self) -> DateTime<Utc> {
        self.started_at
    }

    fn finished_at(&self) -> Option<DateTime<Utc>> {
        self.finished_at
    }

    /// Only for a run that succeeded.
    fn stats(&self) -> Option<RunStats> {
        let stats: ferret_api::internal::RunStats =
            serde_json::from_value(self.stats.clone()?).expect("stored stats are RunStats");
        let count = |n: u64| i32::try_from(n).unwrap_or(i32::MAX);
        Some(RunStats {
            put: count(stats.put),
            unchanged: count(stats.unchanged),
            deleted: count(stats.deleted),
        })
    }

    /// The tail of the run's log.
    fn log(&self) -> &str {
        &self.log
    }

    fn error(&self) -> Option<&str> {
        self.error.as_deref()
    }
}

#[derive(GraphQLInputObject)]
struct NewConnection {
    plugin: String,
    /// The source root, e.g. `notes` or `mail/zoho`. Can't contain or lie below another
    /// connection's root.
    source: String,
    /// The plugin config as JSON text, valid against the plugin's schema.
    config: String,
    /// Cron expression, e.g. `0 * * * *` for hourly.
    schedule: String,
}

#[derive(GraphQLInputObject)]
struct ConnectionUpdate {
    config: String,
    schedule: String,
    enabled: bool,
}

pub struct Mutation;

#[derive(GraphQLInputObject)]
struct NewApiKey {
    name: String,
    scopes: Vec<Scope>,
    /// Restricts every scope to these source paths and below. Leave out for all sources.
    sources: Option<Vec<String>>,
    expires_at: Option<DateTime<Utc>>,
}

/// A new key, with the full key string. The only time it is shown.
struct CreatedApiKey {
    api_key: ApiKey,
    key: String,
}

#[graphql_object(context = Context)]
impl Mutation {
    /// Creates a connection, which runs right away and then on its schedule.
    async fn create_connection(context: &Context, input: NewConnection) -> FieldResult<Connection> {
        let new = connections::NewConnection {
            plugin: input.plugin,
            source: input.source,
            config: parse_config(&input.config)?,
            schedule: input.schedule,
        };
        connections::create(&context.pool, context.user.id, new)
            .await
            .map_err(connection_error)
    }

    async fn update_connection(
        context: &Context,
        id: ID,
        input: ConnectionUpdate,
    ) -> FieldResult<Connection> {
        let update = connections::ConnectionUpdate {
            config: parse_config(&input.config)?,
            schedule: input.schedule,
            enabled: input.enabled,
        };
        connections::update(&context.pool, context.user.id, parse_id(&id)?, update)
            .await
            .map_err(connection_error)?
            .ok_or_else(no_such_connection)
    }

    /// Starts a run without waiting for the schedule. Fails for a disabled connection.
    async fn run_connection_now(context: &Context, id: ID) -> FieldResult<ID> {
        if connections::run_now(&context.pool, context.user.id, parse_id(&id)?)
            .await
            .map_err(internal)?
        {
            Ok(id)
        } else {
            Err(FieldError::new(
                "no such enabled connection",
                graphql_value!(null),
            ))
        }
    }

    /// Deletes the connection and every document below its source root, once `confirmSource`
    /// repeats the root. Returns how many documents were deleted.
    async fn delete_connection(
        context: &Context,
        id: ID,
        confirm_source: String,
    ) -> FieldResult<i32> {
        let deleted = connections::delete(
            &context.pool,
            context.user.id,
            parse_id(&id)?,
            &confirm_source,
        )
        .await
        .map_err(connection_error)?
        .ok_or_else(no_such_connection)?;
        Ok(i32::try_from(deleted).unwrap_or(i32::MAX))
    }

    async fn create_api_key(context: &Context, input: NewApiKey) -> FieldResult<CreatedApiKey> {
        let new = api_keys::NewApiKey {
            name: input.name,
            scopes: input.scopes,
            sources: input.sources,
            expires_at: input.expires_at,
        };
        match api_keys::create(&context.pool, &context.user, new).await {
            Ok((api_key, key)) => Ok(CreatedApiKey { api_key, key }),
            Err(api_keys::CreateError::Invalid(message)) => Err(FieldError::new(
                message,
                graphql_value!({ "code": "INVALID_INPUT" }),
            )),
            Err(api_keys::CreateError::Database(error)) => Err(internal(error)),
        }
    }

    /// Revokes one of the signed-in user's keys and returns its id.
    async fn revoke_api_key(context: &Context, id: ID) -> FieldResult<ID> {
        let not_found = || FieldError::new("no such API key", graphql_value!(null));
        let key_id = id.parse::<Uuid>().map_err(|_| not_found())?;
        if api_keys::revoke(&context.pool, context.user.id, key_id)
            .await
            .map_err(internal)?
        {
            Ok(id)
        } else {
            Err(not_found())
        }
    }
}

#[graphql_object(context = Context)]
impl CreatedApiKey {
    fn api_key(&self) -> &ApiKey {
        &self.api_key
    }

    /// `fk_<prefix>.<secret>`, for `Authorization: Bearer`.
    fn key(&self) -> &str {
        &self.key
    }
}

#[graphql_object(context = Context)]
impl ApiKey {
    fn id(&self) -> ID {
        ID::new(self.id.to_string())
    }

    fn name(&self) -> &str {
        &self.name
    }

    /// The non-secret part after `fk_`, to tell keys apart.
    fn prefix(&self) -> &str {
        &self.prefix
    }

    fn scopes(&self) -> &[Scope] {
        &self.scopes
    }

    /// Source paths every scope is restricted to, null for all sources.
    fn sources(&self) -> Option<&[String]> {
        self.sources.as_deref()
    }

    fn created_at(&self) -> DateTime<Utc> {
        self.created_at
    }

    /// Updated at most once a minute.
    fn last_used_at(&self) -> Option<DateTime<Utc>> {
        self.last_used_at
    }

    fn expires_at(&self) -> Option<DateTime<Utc>> {
        self.expires_at
    }
}

fn parse_config(config: &str) -> FieldResult<serde_json::Value> {
    serde_json::from_str(config)
        .map_err(|error| invalid_input(format!("the config isn't JSON: {error}")))
}

fn parse_id(id: &ID) -> FieldResult<Uuid> {
    id.parse().map_err(|_| no_such_connection())
}

fn no_such_connection() -> FieldError {
    FieldError::new("no such connection", graphql_value!(null))
}

fn connection_error(error: ConnectionError) -> FieldError {
    match error {
        ConnectionError::Invalid(message) => invalid_input(message),
        ConnectionError::Database(error) => internal(error),
    }
}

fn invalid_input(message: String) -> FieldError {
    FieldError::new(message, graphql_value!({ "code": "INVALID_INPUT" }))
}

/// Database failures are logged, the client only learns that something went wrong.
fn internal(error: sqlx::Error) -> FieldError {
    tracing::error!(%error, "database error");
    FieldError::new("internal error", graphql_value!(null))
}

