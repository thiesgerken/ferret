struct EmbeddingModel {
    id: String,
    configured_default: bool,
    min_similarity: f64,
    // Pin coverage fields to one snapshot even if a request spans cache expiry.
    progress: OnceCell<Arc<crate::statistics::Progress>>,
}

/// A configured embedding model and how much of the signed-in user's data it covers. A model
/// can be chosen before it covers everything, its semantic half is partial until then.
#[graphql_object(context = Context)]
impl EmbeddingModel {
    fn id(&self) -> &str {
        &self.id
    }

    /// Whether searches use it when the user chose no default.
    fn configured_default(&self) -> bool {
        self.configured_default
    }

    /// The cosine similarity below which search drops the model's semantic candidates.
    fn min_similarity(&self) -> f64 {
        self.min_similarity
    }

    /// How many of the user's chunks the model has embedded, in a five-second progress snapshot.
    /// Loaded only when progress is requested; the search page lists models without it.
    async fn embedded(&self, context: &Context) -> FieldResult<i32> {
        Ok(count(self.progress(context).await?.embedded))
    }

    /// Total user chunks in the same five-second snapshot as embedded, pending and failed.
    async fn chunks(&self, context: &Context) -> FieldResult<i32> {
        Ok(count(self.progress(context).await?.chunks()))
    }

    /// The user's chunks still waiting for the embed pump.
    async fn pending(&self, context: &Context) -> FieldResult<i32> {
        Ok(count(self.backlog(context).await?.0))
    }

    /// The user's chunks the model's endpoint rejected, which the pump leaves out.
    async fn failed(&self, context: &Context) -> FieldResult<i32> {
        Ok(count(self.backlog(context).await?.1))
    }

    /// Chunks per minute the pump embedded over the last 10 minutes, across users: the pump is
    /// shared.
    async fn rate_per_minute(&self, context: &Context) -> FieldResult<f64> {
        self.rate(context).await
    }

    /// Seconds until `pending` is embedded at `ratePerMinute`. Optimistic while other users'
    /// chunks wait too, the pump shares its rate. Null when nothing is pending or the rate is 0.
    async fn eta_seconds(&self, context: &Context) -> FieldResult<Option<i32>> {
        let (pending, _) = self.backlog(context).await?;
        let rate = self.rate(context).await?;
        Ok(embeddings::eta_seconds(pending, rate).map(count))
    }

    /// Whether the endpoint for search queries answered its last request from the answering
    /// server process. True before the first one.
    fn online(&self, context: &Context) -> bool {
        self.model(context).query_api.health().last_error.is_none()
    }

    /// Whether the endpoint for chunks answered its last request from the answering server
    /// process. While it doesn't, `pending` stays.
    fn embedding(&self, context: &Context) -> bool {
        self.model(context)
            .embedding_api
            .health()
            .last_error
            .is_none()
    }
}

impl EmbeddingModel {
    async fn progress(&self, context: &Context) -> FieldResult<&crate::statistics::Progress> {
        self.progress
            .get_or_try_init(|| {
                context
                    .statistics
                    .progress(&context.pool, context.user.id, &self.id)
            })
            .await
            .map(Arc::as_ref)
            .map_err(internal)
    }

    async fn backlog(&self, context: &Context) -> FieldResult<(i64, i64)> {
        let progress = self.progress(context).await?;
        Ok((progress.pending, progress.failed))
    }

    async fn rate(&self, context: &Context) -> FieldResult<f64> {
        context
            .statistics
            .rate(&context.pool, &self.id)
            .await
            .map_err(internal)
    }

    fn model<'a>(&self, context: &'a Context) -> &'a embeddings::Model {
        context
            .embedding
            .model(&self.id)
            .expect("embeddingModels lists configured models only")
    }
}

/// A document returned by a search, with its best-matching chunk.
#[derive(GraphQLObject)]
struct Hit {
    document_id: ID,
    source: String,
    external_id: String,
    content_type: ContentType,
    title: Option<String>,
    /// Deep link to the origin, null when ferret's viewer is the origin.
    url: Option<String>,
    thread: Option<String>,
    authors: Vec<String>,
    created_at: DateTime<Utc>,
    modified_at: DateTime<Utc>,
    /// The connection or API key that put the document, null for one from before writers were
    /// recorded.
    writer: Option<Writer>,
    /// The best BM25 score among the document's chunks in the keyword half's candidates, null
    /// when none of them is.
    keyword_score: Option<f64>,
    /// The best cosine similarity to the query (0 to 1) among the document's chunks in the vector
    /// half's candidates above the model's cut-off, null when none of them is or the semantic
    /// half didn't run.
    similarity: Option<f64>,
    /// How many more documents of the same thread matched and were folded into this hit.
    collapsed: i32,
    chunk: HitChunk,
    /// Whether the signed-in user marked this document as the right hit for this very search.
    judged: bool,
}

/// The best-matching chunk of a hit. Offsets count characters (Unicode code points) into the
/// document's text.
